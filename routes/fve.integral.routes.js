'use strict';
const router=require('express').Router();
const requirePermissions=require('../middleware/requirePermissions');
const {crearControlador}=require('../controllers/fve.negociacion.controller');
const c=crearControlador();
const leer=requirePermissions(['Obtener diagnósticos']);
const modificar=requirePermissions(['Generar diagnóstico']);
router.get('/procesos/:idProceso/negociacion',leer,c.consultar);
router.get('/procesos/:idProceso/negociacion/diagnostico',leer,c.diagnosticoOrigen);
router.post('/procesos/:idProceso/negociacion/propuesta',modificar,c.prepararPropuesta);
router.post('/procesos/:idProceso/negociacion/presentar',modificar,c.presentar);
router.get('/procesos/:idProceso/negociacion/propuestas/:idPropuesta/pdf',leer,c.descargarPdf);
router.post('/procesos/:idProceso/negociacion/decision',modificar,c.decision);
router.post('/procesos/:idProceso/negociacion/reanudar',modificar,c.reanudar);
router.post('/procesos/:idProceso/negociacion/financiacion',modificar,c.financiacion);
router.post('/procesos/:idProceso/negociacion/viabilidad',modificar,c.viabilidad);
router.post('/procesos/:idProceso/negociacion/reformular',modificar,c.reformular);
router.post('/procesos/:idProceso/negociacion/aceptar',modificar,c.aceptar);
module.exports=router;
